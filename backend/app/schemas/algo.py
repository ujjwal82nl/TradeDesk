"""Algorithmic trading run and signal Pydantic schemas."""

from __future__ import annotations

from datetime import datetime
from typing import Any, Dict, Literal, Optional

from pydantic import BaseModel, Field


class AlgoRunCreate(BaseModel):
    """Payload for launching an algorithmic trading run."""

    name: str = Field(..., min_length=1, description="Human-readable run label.")
    strategy_code: str = Field(
        ..., description="Identifier or full source code of the strategy."
    )
    mode: Literal["PAPER", "LIVE", "BACKTEST"] = Field(
        ..., description="Execution mode."
    )
    config: Dict[str, Any] = Field(
        default_factory=dict,
        description="Strategy-specific configuration parameters.",
    )


class AlgoRunResponse(BaseModel):
    """Serialised algo run record."""

    id: int
    name: str
    status: str = Field(
        ...,
        description="E.g. 'PENDING', 'RUNNING', 'STOPPED', 'ERROR', 'COMPLETED'.",
    )
    mode: str
    started_at: Optional[datetime] = None
    stopped_at: Optional[datetime] = None
    config: Dict[str, Any]

    model_config = {"from_attributes": True}


class TradeSignalResponse(BaseModel):
    """A trade signal generated by an algorithm."""

    id: int
    symbol: str
    exchange: str
    signal_type: str = Field(..., description="'BUY', 'SELL', or 'EXIT'.")
    price: float = Field(..., description="Signal price at the time of generation.")
    quantity: int
    strategy_name: str
    confidence_score: float = Field(
        ..., ge=0.0, le=1.0, description="Model confidence (0-1)."
    )
    executed: bool = Field(..., description="Whether the signal was acted upon.")
    created_at: datetime

    model_config = {"from_attributes": True}


class AlgoStrategyBase(BaseModel):
    name: str = Field(..., min_length=1, max_length=255)
    description: Optional[str] = None
    template_type: str = "CUSTOM"
    underlying: str = "NIFTY"
    broker_account_id: Optional[int] = None
    is_active: bool = False
    mode: str = "LIVE"
    product_type: str = "MIS"
    entry_params: Dict[str, Any] = Field(default_factory=dict)
    exit_params: Dict[str, Any] = Field(default_factory=dict)
    legs: list[Dict[str, Any]] = Field(default_factory=list)


class AlgoStrategyCreate(AlgoStrategyBase):
    pass


class AlgoStrategyUpdate(BaseModel):
    name: Optional[str] = None
    description: Optional[str] = None
    template_type: Optional[str] = None
    underlying: Optional[str] = None
    broker_account_id: Optional[int] = None
    is_active: Optional[bool] = None
    mode: Optional[str] = None
    product_type: Optional[str] = None
    entry_params: Optional[Dict[str, Any]] = None
    exit_params: Optional[Dict[str, Any]] = None
    legs: Optional[list[Dict[str, Any]]] = None


class AlgoStrategyResponse(AlgoStrategyBase):
    id: int
    user_id: int
    last_run_at: Optional[datetime] = None
    created_at: datetime
    updated_at: datetime

    model_config = {"from_attributes": True}


class AlgoTemplatePreset(BaseModel):
    template_id: str
    title: str
    category: str
    description: str
    default_underlying: str
    default_product: str
    entry_params: Dict[str, Any]
    exit_params: Dict[str, Any]
    legs: list[Dict[str, Any]]
